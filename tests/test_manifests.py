#!/usr/bin/env python3

import sys
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fitgirl_installer.verification import manifests  # noqa: E402


class ParseManifestTests(unittest.TestCase):
    def parse(self, content: bytes):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "fitgirl.md5"
            path.write_bytes(content)
            return manifests.parse_manifest(path)

    def test_reads_fitgirl_format_with_bom_comments_and_parent_prefixes(self):
        rows = self.parse(
            b"\xef\xbb\xbf; generated by QuickSFV\r\n"
            b"\r\n"
            b"D41D8CD98F00B204E9800998ECF8427E *..\\..\\Data\\game.pak\r\n"
            b"0cc175b9c0f1b6a831c399e269772661  bin\\a.exe\r\n"
        )
        self.assertEqual(rows, [
            ("d41d8cd98f00b204e9800998ecf8427e", "Data/game.pak"),
            ("0cc175b9c0f1b6a831c399e269772661", "bin/a.exe"),
        ])

    def test_rejects_line_that_is_not_a_digest_entry(self):
        with self.assertRaisesRegex(ValueError, "linha MD5 inválida 2"):
            self.parse(b"; ok\nnot-a-digest *file.bin\n")


if __name__ == "__main__":
    unittest.main()
